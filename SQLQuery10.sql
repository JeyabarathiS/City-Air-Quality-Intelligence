USE AirQualityDB;
GO

SELECT
    CAST(Station AS NVARCHAR(100)) AS Station,
    MAX(TRY_CONVERT(FLOAT, AQI_Value)) AS Highest_AQI
FROM AirQuality
WHERE TRY_CONVERT(FLOAT, AQI_Value) IS NOT NULL
GROUP BY CAST(Station AS NVARCHAR(100))
ORDER BY Highest_AQI DESC;
USE AirQualityDB;
GO

SELECT
    CAST(Station AS NVARCHAR(100)) AS Station,
    COUNT(*) AS High_AQI_Count
FROM AirQuality
WHERE TRY_CONVERT(FLOAT, AQI_Value) > 150
GROUP BY CAST(Station AS NVARCHAR(100))
ORDER BY High_AQI_Count DESC;
USE AirQualityDB;
GO

SELECT
    CAST(Station AS NVARCHAR(100)) AS Station,
    ROUND(AVG(TRY_CONVERT(FLOAT, AQI_Value)), 2) AS Average_AQI
FROM AirQuality
WHERE TRY_CONVERT(FLOAT, AQI_Value) IS NOT NULL
GROUP BY CAST(Station AS NVARCHAR(100))
ORDER BY Average_AQI DESC;