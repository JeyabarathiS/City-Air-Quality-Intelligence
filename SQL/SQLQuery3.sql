USE AirQualityDB;
GO
SELECT 
	COUNT(*) AS Total_Records,
	SUM(CASE WHEN AQI_Index IS NULL
		THEN 1 ELSE 0 END) AS Missing_AQI_Category,
	SUM(CASE WHEN AQI_Value IS NULL 
		THEN 1 ELSE 0 END) AS Missing_AQI_Value,
	SUM(CASE WHEN PM2_5 IS NULL 
		THEN 1 ELSE 0 END) AS Missing_PM25,
	SUM(CASE WHEN PM10 IS NULL 
		THEN 1 ELSE 0 END) AS Missing_PM10
FROM AirQuality;
